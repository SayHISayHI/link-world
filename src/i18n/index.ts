export type Translator = (message: string, variables?: Variables) => string;

export function translate(locale: AppLocale, message: string, variables?: Variables): string {
  const template = locale === "zh-CN" ? (zhCN.get(message) ?? message) : message;
  if (!variables) return template;

  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match,
  );
}

export function useI18n() {
  const locale = useUiStore((state) => state.locale);
  const t = useCallback<Translator>(
    (message, variables) => translate(locale, message, variables),
    [locale],
  );

  return { locale, t };
}

export function localeTag(locale: AppLocale) {
  return locale === "zh-CN" ? "zh-CN" : "en-US";
}
